// One-off: emit src/foil/promo-db.ts from tmp/promo/claims.json.
import { readFileSync, writeFileSync } from 'node:fs'

const claims = JSON.parse(readFileSync('tmp/promo/claims.json', 'utf8'))
const { bySet } = claims

const rows = (treatment) =>
  claims.claims
    .filter((c) => c.treatment === treatment)
    .map((c) => {
      const extra = c.alsoNonHolo ? ', alsoNonHolo: true' : ''
      return `  { cardId: '${c.id}', setId: '${c.setId}', number: '${c.number}', name: ${JSON.stringify(c.name)}${extra} },`
    })
    .join('\n')

// The three rows no catalogue classifies. Each carries the reason it stays open,
// because "unknown" is an answer and a blanket assignment is not.
const unlistedWhy = {
  'np-3': 'Neither treatment catalogue lists it and Bulbapedia’s page mentions no foil. TCGdex’s variant flags for this promo are self-contradictory (holo and normal both false, reverse true), so they are not evidence of a foil.',
  'np-8': 'Neither treatment catalogue lists it and Bulbapedia’s page mentions no foil. TCGdex’s variant flags for this promo are self-contradictory (holo and normal both false, reverse true), so they are not evidence of a foil.',
  'np-10': 'Neither treatment catalogue lists it and Bulbapedia’s page mentions no foil. TCGdex’s variant flags for this promo are self-contradictory (holo and normal both false, reverse true), so they are not evidence of a foil.',
}

const unlisted = claims.unclaimed
  .map((c) => `  { cardId: '${c.id}', setId: '${c.setId}', number: '${c.number}', name: ${JSON.stringify(c.name)}, why: ${JSON.stringify(unlistedWhy[c.id] ?? 'unclassified')} },`)
  .join('\n')

const out = `// GENERATED by tmp/emit-promo-db.mjs — do not hand-edit.
//
// The four pre-2012 Black Star Promo programmes, card by card, from Pokumon's two
// published treatment catalogues (https://pokumon.com/holofoil/cosmos/ and
// https://pokumon.com/holofoil/non-holo/), read ${new Date().toISOString().slice(0, 10)}.
//
// Bulbapedia's promo set pages tag only the exceptional printings, so they cannot
// answer "what foil is on THIS promo?" for the whole set; Pokumon assigns a
// treatment to every card it catalogues, which is what makes a per-card claim
// possible at all. A card listed in neither catalogue makes NO claim here.
//
// Six cards are answered outside this table, by their own pages:
//   - DP54 Beginning Door and DP55 Ultimate Zone: Bulbapedia names a Cosmos Holofoil
//     DP Black Star Promo version of each, released exclusively in French. They live
//     in printing-db.ts's PROMO_ENTRIES because the source is the card page, not a
//     catalogue, and Pokumon's non-holo tag on the same cards is recorded there.
//   - HGSS16 Plusle, HGSS17 Minun, HGSS24 Hitmonchan, HGSS25 Hitmonlee: named Cracked
//     Ice Holofoil prints, so they live in CRACKED_ICE_ENTRIES.
//
// Counts: Wizards ${bySet.basep.cosmos} Cosmos / ${bySet.basep.nonHolo} non-holo / ${bySet.basep.unclaimed} unlisted;
// Nintendo ${bySet.np.cosmos} / ${bySet.np.nonHolo} / ${bySet.np.unclaimed}; DP ${bySet.dpp.cosmos} / ${bySet.dpp.nonHolo} / ${bySet.dpp.unclaimed};
// HGSS ${bySet.hsp.cosmos} / ${bySet.hsp.nonHolo} / ${bySet.hsp.unclaimed}.

export type PromoClaim = {
  cardId: string
  setId: string
  number: string
  /** Guards the table against a card id drifting to a different card. */
  name: string
  /** The same card is also catalogued in the other treatment. */
  alsoNonHolo?: boolean
}

/** Promos Pokumon catalogues on Cosmos — the retro sheet: every one predates 2013. */
export const PROMO_COSMOS_CARDS: readonly PromoClaim[] = [
${rows('cosmos')}
]

/** Promos Pokumon catalogues as non-holo. */
export const PROMO_NON_HOLO_CARDS: readonly PromoClaim[] = [
${rows('non-holo')}
]

/**
 * Rows neither catalogue lists, with the reason each stays open. They keep making no
 * claim rather than being swept into either bucket: an unlisted promo is unknown, not
 * plain, and the reason is what makes that visible instead of silent.
 */
export const PROMO_UNLISTED_CARDS: readonly (PromoClaim & { why: string })[] = [
${unlisted}
]

const CLAIM_BY_ID = new Map<string, { claim: PromoClaim; treatment: 'cosmos' | 'non-holo' | 'unlisted' }>()
for (const claim of PROMO_COSMOS_CARDS) CLAIM_BY_ID.set(claim.cardId, { claim, treatment: 'cosmos' })
for (const claim of PROMO_NON_HOLO_CARDS) CLAIM_BY_ID.set(claim.cardId, { claim, treatment: 'non-holo' })
for (const claim of PROMO_UNLISTED_CARDS) CLAIM_BY_ID.set(claim.cardId, { claim, treatment: 'unlisted' })

export function promoClaimFor(cardId: string) {
  return CLAIM_BY_ID.get(cardId) ?? null
}

export const PROMO_CATALOGUE = {
  source: 'https://pokumon.com/holofoil/cosmos/',
  nonHoloSource: 'https://pokumon.com/holofoil/non-holo/',
  read: '${new Date().toISOString().slice(0, 10)}',
  counts: {
    cosmos: ${bySet.basep.cosmos + bySet.np.cosmos + bySet.dpp.cosmos + bySet.hsp.cosmos},
    nonHolo: ${bySet.basep.nonHolo + bySet.np.nonHolo + bySet.dpp.nonHolo + bySet.hsp.nonHolo},
    unlisted: ${bySet.basep.unclaimed + bySet.np.unclaimed + bySet.dpp.unclaimed + bySet.hsp.unclaimed},
  },
} as const
`

writeFileSync('src/foil/promo-db.ts', out)
console.log('wrote src/foil/promo-db.ts', out.length, 'bytes')
console.log('cosmos', rows('cosmos').split('\n').length, 'non-holo', rows('non-holo').split('\n').length, 'unlisted', claims.unclaimed.length)
