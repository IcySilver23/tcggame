import fs from 'node:fs'

const rows = JSON.parse(fs.readFileSync('tmp/bb-final.json', 'utf8'))
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const body = rows
  .map((r) => {
    const promos = r.promos.map((p) => q(p.name)).join(', ')
    const ids = r.promos.map((p) => q(p.id)).join(', ')
    return `  {
    setId: ${q(r.setId)}, expansion: ${q(r.expansion)}, releaseDate: ${q(r.releaseDate ?? '')},
    promos: [${promos}], promoIds: [${ids}], promoSet: ${q(r.promoSet ?? r.setId)},
    productId: ${r.productId ?? 'null'}, market: ${r.market ?? 'null'}, image: ${r.image ? q(r.image) : 'null'},
  },`
  })
  .join('\n')

const out = `// GENERATED by tmp/gen-build-battle.mjs — do not hand-edit.
//
// One row per expansion that shipped a Build & Battle Box, from Bulbapedia's
// list (the product introduced with Fates Collide and released with every main
// expansion since). \`promos\` are the four possible prerelease cards, in the
// source's order; the box holds one of them. \`productId\`, \`market\` and
// \`image\` come from the tcgcsv mirror (TCGplayer) where it lists the box; the
// older boxes it does not carry keep null and are priced by the model.
//
// TCGplayer does not list a box for every expansion, so \`market\` is null on
// exactly those rows: a null is "no quote here", never a zero price.

export type BuildBattleBox = {
  setId: string
  expansion: string
  releaseDate: string
  promos: string[]
  promoIds: string[]
  promoSet: string
  productId: number | null
  market: number | null
  image: string | null
}

export const BUILD_BATTLE_BOXES: BuildBattleBox[] = [
${body}
]
`
fs.writeFileSync('server/catalog/build-battle.ts', out)
console.log('wrote server/catalog/build-battle.ts with', rows.length, 'rows')
