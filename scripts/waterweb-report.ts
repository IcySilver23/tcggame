// Water Web report: what the paper is, which cards wear it, and what is not claimed.
//
// Run: ./node_modules/.bin/tsx scripts/waterweb-report.ts
//
// The claims stay apart, as every other paper report does:
//
//   identified  Bulbapedia names Water Web for standard Holo cards from Sun & Moon to
//               Cosmic Eclipse and describes "a wavy pattern similar to flowing water";
//               its Rarity page adds that these cards "refract light in a wave-like
//               pattern in all releases", with the border covered only on Japanese
//               printings. That is a SET-level statement: no printing record claims one.
//   painted     a procedural reconstruction: eight wavy bands, undulating down the card,
//               over foil that never goes dark.
//   not claimed the band count, the amplitude, the vertical cycles and the swell; and the
//               Japanese foil border, which this English catalogue does not carry.

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { holoFor } from '../src/holo'
import { printingFor } from '../src/foil/printing-db'
import { foilMaskFor } from '../src/foil/mask'
import { PATTERNS } from '../src/foil/patterns'
import { WATERWEB_CLAIM, WATERWEB_LIMITATION, WATERWEB_SHEET } from '../src/foil/waterweb-index'

const problems: string[] = []

const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare('select id, set_id, number, rarity, name from cards order by set_id, cast(number as integer)')
  .all() as { id: string; set_id: string; number: string; rarity: string | null; name: string }[]
db.close()

type Row = {
  cardId: string
  setId: string
  number: string
  name: string
  rarity: string | null
  style: string
  pattern: string | null
  mask: string | null
  maskVerified: boolean | null
}

const cards: Row[] = []
for (const row of rows) {
  const art = holoFor({ cardId: row.id, rarity: row.rarity ?? undefined })
  // A reverse printing of a Sun & Moon card carries the set's reverse paper; the standard
  // holo behind it is what this report counts, once, and it is the one this paper paints.
  if (art?.style !== 'waterweb' || art.pattern) continue
  const printing = printingFor({ cardId: row.id, rarity: row.rarity ?? undefined, name: row.name })
  const spec = foilMaskFor({ cardId: row.id, rarity: row.rarity ?? undefined })
  cards.push({
    cardId: row.id,
    setId: row.set_id,
    number: row.number,
    name: row.name,
    rarity: row.rarity,
    style: art.style,
    pattern: printing?.pattern ?? null,
    mask: spec?.kind ?? null,
    maskVerified: spec?.verified ?? null,
  })
}

if (!cards.length) problems.push('no card resolves to Water Web')
if (cards.some((c) => c.pattern !== null)) problems.push('a Water Web row carries a printing pattern; the report expects era-level rows only')

const setIds = [...new Set(cards.map((c) => c.setId))].sort()
const perSet = setIds.map((setId) => ({ setId, cards: cards.filter((c) => c.setId === setId) }))
if (!setIds.some((s) => s.startsWith('sm'))) problems.push('no Sun & Moon set resolves to Water Web')
// Detective Pikachu (det1) is in the era's set prefix but carries no Water Web card — its
// rarities stop at Rare Ultra, which resolves to the etched chase finish — so it is not
// counted and not claimed. The era check below covers what remains.
if (setIds.length < 12) problems.push('the era is under-covered')
if (setIds.some((s) => /^(swsh|sv|me|xy)/.test(s))) problems.push('a later or earlier era is being painted with Water Web')

if (PATTERNS.waterweb.implemented !== true) problems.push('the registry does not report Water Web as painted')
if (PATTERNS.waterweb.texture !== WATERWEB_SHEET.pattern) problems.push('the registry points at a different sheet than the generated index')
if (!fs.existsSync('public' + WATERWEB_SHEET.pattern)) problems.push('the sheet the registry points at is not shipped')

const counts = {
  claimed: cards.length,
  painted: PATTERNS.waterweb.implemented ? cards.length : 0,
  sets: setIds.length,
  sunMoonSets: perSet.filter((s) => s.setId.startsWith('sm')).length,
  maskVerified: cards.filter((c) => c.maskVerified).length,
  textureVerified: WATERWEB_SHEET.textureVerified,
  coverage: WATERWEB_SHEET.coverage,
  valley: WATERWEB_SHEET.valley,
  crest: WATERWEB_SHEET.peak,
  contrast: WATERWEB_SHEET.peak / WATERWEB_SHEET.valley,
  seamMismatch: WATERWEB_SHEET.seamMismatch,
  waves: WATERWEB_SHEET.waves,
  measuredFromCards: false,
}

const md = `# Water Web printings

Generated by \`scripts/waterweb-report.ts\`.

**${WATERWEB_CLAIM}**

## Counts

| | |
| --- | --- |
| Cards the catalogue resolves to Water Web | ${counts.claimed} |
| Painted (procedural wave sheet) | ${counts.painted} |
| Sets | ${counts.sets} |
| Sun & Moon sets | ${counts.sunMoonSets} |
| Rows answered by a printing record | 0 — the paper is identified per SET |
| Foil area verified | ${counts.maskVerified} of ${counts.claimed} |
| Texture verified against a card | ${counts.textureVerified ? 'yes' : 'no — the sheet is a drawing'} |
| Bands across the sheet | ${counts.waves} |
| Confirmed against real cards | no — the footage gave no stable period |
| Coverage above the mark line | ${(counts.coverage * 100).toFixed(2)}% |
| Valley / crest | ${counts.valley.toFixed(3)} / ${counts.crest.toFixed(3)} |
| Crest-to-valley contrast | ${counts.contrast.toFixed(2)}× |
| Wrap step when the sheet meets itself | ${(counts.seamMismatch * 100).toFixed(2)}% |

## Per set

| Set | Cards | First examples |
| --- | --- | --- |
${perSet
  .map((s) => `| ${s.setId} | ${s.cards.length} | ${s.cards.slice(0, 4).map((c) => c.name).join(', ')}${s.cards.length > 4 ? ', …' : ''} |`)
  .join('\n')}

## What is painted, and what that claim is

\`public/foil/waterweb/sheet.png\` is a **procedural reconstruction**: ${counts.waves} wavy bands
across the sheet, each undulating twice on its way down, over foil whose valleys stay bright
(${counts.valley.toFixed(3)}) because Water Web is a continuous foil with waves in it rather than
bright ribbons on a black field.

The sources are thin and the report does not pretend otherwise. Bulbapedia names the era and says
the pattern is "similar to flowing water"; its Rarity page says these cards "refract light in a
wave-like pattern"; a 2021 Bleeding Cool piece describes "wavey lines that almost look like
psychedelic water stains" that move "like waves crashing on a beach shore" when the card tilts.
None of them gives a band count, an amplitude or a repeat, so those are this build's drawing and the
index says so.

It **wraps**: the step across the two edges that meet is no larger than the step between two
neighbouring columns inside the sheet, which is one pixel of a band's own slope. Whether the real
paper repeated is undocumented, so the wrap is this build's disclosed choice.

Copy variation is a **crop**, not a re-seed: each card id derives its own offset and a slight zoom.
A save does not distinguish physical copies, so two copies of one card id share a cut.

## Measured against real cards

\`tmp/measure-papers.py\` measures the printed spacing on a SINGLE 1080p frame, because a
frame-to-frame ratio divides one tilt by another and, under a separable foil model, divides the
printed pattern out along with the artwork. The card is found from its edge energy, its art window
is detrended row by row, and the mean row autocorrelation is taken in luminance and in both
colour-opponent channels, since this sheen carries much of its contrast in hue.

The control — this build's own eight-band pattern drawn over textured artwork — reads 0.1718 card
widths against the sheet's 0.1743, and the same artwork with no foil produces no peak. The real
cards do not confirm it: across five frames of a Sun & Moon Rhyperior the strongest autocorrelation
inside the expected band is r = 0.04–0.14 at 0.26–0.30 card widths, which is noise and outside the
band. The footage holds the card at a steep angle, where perspective varies the horizontal scale
across the face, and the bands are broad and irregular there. **The eight bands therefore remain
this build's drawing, not a measurement.**

## What the identification covers, and what it does not

${WATERWEB_LIMITATION}

Two consequences follow. Every row here is an **era-level** identification: \`holo.ts\` maps the set
prefix to Water Web for standard holos, and no printing record claims one, so the count is how many
cards change — it is not a per-card verification. And the foil AREA is the renderer's ordinary
illustration-window default (${counts.maskVerified} of ${counts.claimed} rows carry a verified mask),
because the source describes the pattern and the border side, not which cells of the face carry it.

## Validation

\`tmp/check-waterweb.ts\` proves: the bands are wavy (a crest column varies by more than a quarter of
the ink range down the sheet, which a ruled paper would not), there are eight crests across a row,
the phase is a whole number of turns in both axes, the field wraps, keeps its valleys bright,
renders deterministically and carries no colour; the shipped PNG and the index agree; the sampler
cuts one stable window per card and different windows per card; Sun & Moon and Detective Pikachu
resolve here while Sword & Shield keeps Line and Scarlet & Violet keeps Mirage, and a reverse
printing keeps its own paper; the registry reports it painted and points at the shipped file; and a
render at rest is the scan byte for byte while a tilted one adds light only inside the mask.

It does **not** confirm the sheet against a photograph: the attempt above measured real cards and
found no stable period to compare.
`

const report = {
  generated: 'scripts/waterweb-report.ts',
  phase: 'Water Web painted',
  claims: {
    identified: WATERWEB_CLAIM,
    limitation: WATERWEB_LIMITATION,
    painted: 'procedural reconstruction; not a scan',
    relief: 'not claimed',
  },
  sheet: WATERWEB_SHEET,
  counts,
  sets: perSet.map((s) => ({ setId: s.setId, cards: s.cards.length })),
  cards,
  problems,
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/waterweb-printings.json', JSON.stringify(report, null, 2) + '\n')
fs.writeFileSync('reports/waterweb-printings.md', md)

console.log(`Water Web: ${counts.claimed} cards across ${counts.sets} sets of the Sun & Moon era, painted ${counts.painted}`)
console.log(`  ${counts.waves} bands, coverage ${(counts.coverage * 100).toFixed(2)}%, valley/crest ${counts.valley.toFixed(3)}/${counts.crest.toFixed(3)}, seam ${(counts.seamMismatch * 100).toFixed(2)}%`)
console.log(`  problems: ${problems.length}`)
for (const p of problems) console.log(`  - ${p}`)
if (problems.length) process.exit(1)
