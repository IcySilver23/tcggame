// Phase 5I report: the Sword & Shield tile reverse paper.
//
// Run: ./node_modules/.bin/tsx scripts/reverse-tile-report.ts

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { REVERSE_EXPANSIONS, reverseEligible } from '../src/foil/reverse-db'
import { REVERSE_TILE_ASSETS, REVERSE_TILE_TEXTURE_VERIFIED, REVERSE_TILE_SHOWCASE } from '../src/foil/reverse-tile-index'
import { glyphForCard } from '../src/foil/type-symbol'

const SETS = REVERSE_EXPANSIONS.filter((e) => e.pattern === 'reverse-tile')

type Row = { set_id: string; number: string; rarity: string | null; types: string | null; supertype: string | null }
const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare(`select set_id, number, rarity, types, supertype from cards where set_id in (${SETS.map(() => '?').join(',')})`)
  .all(...SETS.map((e) => e.setId)) as Row[]
db.close()

const eligible = rows.filter((r) => reverseEligible({ setId: r.set_id, number: r.number, rarity: r.rarity }))
const usable = eligible.filter((r) => glyphForCard({ types: r.types, supertype: r.supertype }) !== null)

const problems: string[] = []
for (const e of SETS) {
  if (e.mask !== 'outside-art') problems.push(`${e.setId}: mask is ${e.mask}, expected the card body`)
  if (!e.implemented) problems.push(`${e.setId}: not marked validated`)
}
for (const [id, a] of Object.entries(REVERSE_TILE_ASSETS)) {
  if (!fs.existsSync('public' + a.texture)) problems.push(`${id}: texture not shipped`)
  if (a.seam > 0.05) problems.push(`${id}: seam ${a.seam} too high`)
}

const counts = {
  expansions: SETS.length,
  validated: SETS.filter((e) => e.implemented).length,
  glyphs: Object.keys(REVERSE_TILE_ASSETS).length,
  reversePrintings: eligible.length,
  printingsWithKnownType: usable.length,
  textureVerified: REVERSE_TILE_TEXTURE_VERIFIED,
  showcase: REVERSE_TILE_SHOWCASE.length,
}

const report = {
  generated: 'scripts/reverse-tile-report.ts',
  phase: 'Phase 5I — Sword & Shield tile paper',
  counts,
  expansions: SETS.map((e) => ({ setId: e.setId, name: e.name, year: e.year, mask: e.mask, implemented: e.implemented })),
  glyphs: Object.entries(REVERSE_TILE_ASSETS).map(([id, a]) => ({
    id, label: a.label, texture: a.texture, coverage: a.coverage, peak: a.peak, seam: a.seam,
  })),
  problems,
  honesty: [
    'Bulbapedia describes tiles each containing the type symbol or a Poké Ball. That identifies the paper, not its exact geometry or artwork.',
    'The lattice and glyphs are procedural drawings made for this build, not official icons, and none is verified against a photograph.',
    'The sheet tiles with a staggered lattice; whether the real print repeated exactly is undocumented, so tiling is this build\'s disclosed choice.',
    'The type comes from the card; an unknown type renders plain foil rather than the wrong symbol.',
    `Of ${eligible.length} reverse printings here, ${usable.length} have a usable type; the rest show plain foil.`,
  ],
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/reverse-tile-printings.json', JSON.stringify(report, null, 2) + '\n')
const lines = [
  '# Sword & Shield tile paper',
  '',
  `Generated by \`${report.generated}\`. Phase 5I of \`HOLOFOIL_ROADMAP.md\`.`,
  '',
  '## Numbers',
  '',
  `- Expansions on this paper: **${counts.expansions}** (${counts.validated} validated).`,
  `- Reverse printings: **${counts.reversePrintings}**; usable type: ${counts.printingsWithKnownType}.`,
  `- Tile sheets: **${counts.glyphs}**; texture verified: ${counts.textureVerified ? 'yes' : 'no — stylised reconstruction'}.`,
  '',
  '## What is verified and what is drawn',
  '',
  ...report.honesty.map((h) => `- ${h}`),
  '',
  '## Expansions',
  '',
  '| set | name | mask | validated |',
  '| --- | --- | --- | --- |',
  ...report.expansions.map((e) => `| \`${e.setId}\` | ${e.name} | ${e.mask === 'outside-art' ? 'body' : 'window'} | ${e.implemented ? 'yes' : 'no'} |`),
  '',
]
if (problems.length) lines.push('## Problems', '', ...problems.map((p) => `- ${p}`), '')
fs.writeFileSync('reports/reverse-tile-printings.md', lines.join('\n'))

console.log(`expansions: ${counts.expansions} (${counts.validated}) · printings: ${counts.reversePrintings} · usable type: ${counts.printingsWithKnownType}`)
console.log('written: reports/reverse-tile-printings.json, reports/reverse-tile-printings.md')
if (problems.length) { for (const p of problems) console.log(' -', p); process.exitCode = 1 }
else console.log('all 15 expansions use the body mask and are validated')
