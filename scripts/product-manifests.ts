import fs from 'node:fs'
import { allProductManifests, manifestSummary, type ManifestFieldName, type ManifestStatus, type ProductManifest } from '../server/services/product-manifest'
import { ensureFullCatalog } from '../server/services/sealed'

// Writes the full per-product manifest and a readable audit.
//
// The JSON is the manifest; the Markdown is the same data with the questions a
// reader actually asks first: how many products are sourced, which fields are
// unverified, and what the three mini packs and five 30C products contain.

// New product rows are created by the same boot path the shop uses, so the
// report includes the special-set bundles the catalogue now knows about.
ensureFullCatalog()
const manifests = allProductManifests()
const summary = manifestSummary(manifests)

const fieldNames: ManifestFieldName[] = ['counts', 'layout', 'promos', 'hitTiers', 'foil']
const statuses: ManifestStatus[] = ['verified', 'inferred', 'modelled', 'unverified']

const fieldLabel: Record<ManifestFieldName, string> = {
  counts: 'Pack counts',
  layout: 'Layout',
  promos: 'Promos',
  hitTiers: 'Hit tiers',
  foil: 'Foil guarantees',
}

const shortStatus: Record<ManifestStatus, string> = {
  verified: 'V',
  inferred: 'I',
  modelled: 'M',
  unverified: 'U',
}

function esc(s: string): string {
  return s.replace(/\|/g, '\\|')
}

function specialRows(m: ProductManifest): boolean {
  return m.kind === 'special' || m.productId.startsWith('gm-')
}

const special = manifests.filter(specialRows)
const unverifiedProducts = manifests
  .map((m) => ({
    m,
    fields: fieldNames.filter((f) => m[f].status === 'unverified'),
  }))
  .filter((r) => r.fields.length > 0)

const sources = new Map<string, { label: string; url: string | null }>()
for (const m of manifests) for (const s of m.sources) sources.set(`${s.label}|${s.url ?? ''}`, s)

const md: string[] = []
md.push('# Per-product manifests')
md.push('')
md.push('Generated by `scripts/product-manifests.ts`. The JSON beside this file is the complete manifest; this page is the audit view.')
md.push('')
md.push('Every product answers five questions — pack counts, layout, promos, hit tiers and foil guarantees — with one of four statuses:')
md.push('')
md.push('| Status | Meaning |')
md.push('| --- | --- |')
md.push('| `verified` | A source names this product or the physical rule it follows. |')
md.push('| `inferred` | A verified set or era rule applied to a product no source names. |')
md.push('| `modelled` | This build’s own choice, disclosed as such. |')
md.push('| `unverified` | No source here, and the value is `null`. The manifest does not guess. |')
md.push('')
md.push('## Summary')
md.push('')
md.push('| | |')
md.push('| --- | ---: |')
md.push(`| Products | ${summary.products.toLocaleString('en-US')} |`)
md.push(`| Sold products | ${summary.sold.toLocaleString('en-US')} |`)
md.push(`| Hidden pull-table hosts | ${summary.hidden.toLocaleString('en-US')} |`)
md.push('')
md.push('| Verdict | Products |')
md.push('| --- | ---: |')
for (const v of ['verified', 'inferred', 'modelled', 'partial', 'unsourced'] as const) {
  md.push(`| ${v} | ${summary.verdicts[v].toLocaleString('en-US')} |`)
}
md.push('')
md.push('### Field coverage')
md.push('')
md.push('| Field | Verified | Inferred | Modelled | Unverified |')
md.push('| --- | ---: | ---: | ---: | ---: |')
for (const f of fieldNames) {
  const c = summary.fields[f]
  md.push(`| ${fieldLabel[f]} | ${c.verified} | ${c.inferred} | ${c.modelled} | ${c.unverified} |`)
}
md.push('')
md.push('`partial` means at least one of the five fields is unverified; `modelled` means the answer exists but includes a build choice; `unsourced` is a hidden pull-table host with no product wrapper.')
md.push('')
md.push('## The sourced special products')
md.push('')
md.push('These are the rows with product-level copy rather than a generated set format.')
md.push('')
md.push('`V` verified · `I` inferred · `M` modelled · `U` unverified. A status applies to the whole cell beside it.')
md.push('')
md.push('| Product | Packs | Game / physical cards | Promo | Hit tiers | Foil |')
md.push('| --- | ---: | ---: | --- | --- | --- |')
for (const m of special) {
  const c = m.counts.value
  const promo = m.promos.value
    ? m.promos.value.map((p) => `${p.name}${p.guaranteed ? ' (guaranteed)' : ` (${pctNum(p.chance)})`}`).join(', ')
    : `unverified — ${m.promos.note}`
  const hits = m.hitTiers.value
    ? m.hitTiers.value.length > 0
      ? m.hitTiers.value.map((h) => `${h.name} ${pctNum(h.odds)}`).join(', ')
      : 'none'
    : 'unverified'
  const foil = m.foil.value
    ? m.foil.value.map((f) => `${f.label}${f.guarantee === 'every-pack' ? ' (every pack)' : f.guarantee === 'chance' ? ` (${f.odds == null ? 'chance not sourced' : pctNum(f.odds)})` : ''}`).join(', ')
    : 'unverified'
  md.push(`| ${esc(m.name)} | ${c?.packs ?? '—'} (${shortStatus[m.counts.status]}) | ${c?.cardsPerPack ?? '—'} / ${c?.physicalTotalCards ?? '—'} (${shortStatus[m.counts.status]}) | ${esc(promo)} (${shortStatus[m.promos.status]}) | ${esc(hits)} (${shortStatus[m.hitTiers.status]}) | ${esc(foil)} (${shortStatus[m.foil.status]}) |`)
}
md.push('')
md.push('## Explicitly unverified')
md.push('')
md.push('A field appears here only when its value is `null`. The two recurring causes are a generic ETB promo (the opener synthesises one, the catalogue does not map it) and a hidden pull-table host with no product wrapper.')
md.push('')
md.push('| Product | Kind | Unverified fields | Why |')
md.push('| --- | --- | --- | --- |')
for (const { m, fields } of unverifiedProducts) {
  const why = fields.map((f) => `${fieldLabel[f]}: ${m[f].note}`).join(' ')
  md.push(`| ${esc(m.name)} | ${m.kind} | ${fields.map((f) => fieldLabel[f]).join(', ')} | ${esc(why)} |`)
}
md.push('')
md.push('## Every product')
md.push('')
md.push('`V` verified · `I` inferred · `M` modelled · `U` unverified (value `null`).')
md.push('')
md.push('| Product | Kind | Packs | Counts | Layout | Promos | Hit tiers | Foil | Verdict |')
md.push('| --- | --- | ---: | --- | --- | --- | --- | --- | --- |')
for (const m of manifests) {
  md.push(`| ${esc(m.name)} | ${m.kind} | ${m.counts.value?.packs ?? '—'} | ${shortStatus[m.counts.status]} | ${shortStatus[m.layout.status]} | ${shortStatus[m.promos.status]} | ${shortStatus[m.hitTiers.status]} | ${shortStatus[m.foil.status]} | ${m.status} |`)
}
md.push('')
md.push('## Sources')
md.push('')
md.push('| Source | URL |')
md.push('| --- | --- |')
for (const s of sources.values()) md.push(`| ${esc(s.label)} | ${s.url ? `<${s.url}>` : '—'} |`)
md.push('')
md.push('## What this does not claim')
md.push('')
md.push('- **A generic ETB/bundle/display is not 1:1.** The catalogue applies one pack count and one layout to the whole kind. The manifest marks those counts `modelled` rather than copying the set’s booster odds and calling it product-specific.')
md.push('- **A synthesised ETB promo is not the real promo.** The field is `unverified` with `value: null`; the opener’s deterministic pick remains a game mechanic, not a sourced box list.')
md.push('- **30th Celebration is a ten-card abstraction.** The physical wrapper is six cards. The game stretches it to ten, and the manifest says so instead of presenting the deal as the wrapper.')
md.push('- **The 30C UPC’s three-card Classic pack is not opened.** The pack count and physical total include it; the layout records it under `omitted`.')
md.push('- **Hit tiers are the era model unless a set has its own sample.** The source line in each field says which kind of claim it is. Estimated eras are `modelled`.')
md.push('- **No product photo or wrapper checklist was used for a generic product.** A per-product source is what would promote its fields from `modelled` to `verified`.')

const report = {
  generated: 'scripts/product-manifests.ts',
  summary,
  products: manifests,
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/product-manifests.json', JSON.stringify(report, null, 2) + '\n')
fs.writeFileSync('reports/product-manifests.md', md.join('\n') + '\n')

console.log(`Manifests: ${summary.products} products, ${summary.sold} sold, ${summary.hidden} hidden`)
console.log(`  verdicts: ${JSON.stringify(summary.verdicts)}`)
console.log('  written: reports/product-manifests.{json,md}')

function pctNum(n: number): string {
  return `${(n * 100).toFixed(1).replace(/\.0$/, '')}%`
}
