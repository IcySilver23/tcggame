import { mkdirSync, writeFileSync } from 'node:fs'
import { db } from '../server/lib/db'
import { allProductManifests, type ProductManifest } from '../server/services/product-manifest'
import { ensureFullCatalog, sellsProduct, PULL_TABLE_HOSTS } from '../server/services/sealed'
import { SEALED_EVIDENCE, UNSELLABLE_PRODUCTS, unsellableReason } from '../server/catalog/sealed-evidence'

// Audits the modern ETB, bundle and display rows against the per-product
// evidence table. Writes reports/sealed-evidence.{json,md}.
//
// The table is the claim; this report is the measurement. A count that disagrees
// with the table, a named promo that the manifest does not carry, or a product
// the evidence knows about but the catalogue lacks is a failure, not a warning.

type ModernRow = {
  id: string
  set_id: string
  name: string
  kind: string
  packs: number | null
  msrp: number
  release_date: string
  set_name: string
}

ensureFullCatalog()
const manifests = new Map(allProductManifests().map((m) => [m.productId, m]))
const evidenceIds = Object.keys(SEALED_EVIDENCE).sort()

const modern = db
  .prepare(
    `SELECT p.id, p.set_id, p.name, p.kind, p.packs, p.msrp, p.release_date, s.name AS set_name
     FROM pack_products p JOIN sets s ON s.id = p.set_id
     WHERE s.release_date >= '2023-01-01'
     ORDER BY s.release_date DESC, p.id`,
  )
  .all() as ModernRow[]

const missing = evidenceIds.filter((id) => !manifests.has(id))
const mismatches: { id: string; field: string; expected: string; actual: string }[] = []

for (const id of evidenceIds) {
  const evidence = SEALED_EVIDENCE[id]
  const m = manifests.get(id)
  if (!m) continue
  const actualPacks = m.counts.value?.packs ?? null
  if (actualPacks !== evidence.packs) {
    mismatches.push({ id, field: 'packs', expected: String(evidence.packs), actual: String(actualPacks) })
  }
  const actualPromos = (m.promos.value ?? []).map((p) => p.name).sort()
  const expectedPromos = [...evidence.promos].sort()
  if (actualPromos.join('|') !== expectedPromos.join('|')) {
    mismatches.push({ id, field: 'promos', expected: expectedPromos.join(', ') || '(none)', actual: actualPromos.join(', ') || '(none)' })
  }
}

const removed = Object.keys(UNSELLABLE_PRODUCTS)
  .filter((id) => !PULL_TABLE_HOSTS.has(id))
  .sort()
  .map((id) => ({ id, reason: unsellableReason(id)!, present: manifests.has(id) }))
const removedStillPresent = removed.filter((x) => x.present)

const audited = evidenceIds.map((id) => manifests.get(id)).filter((m): m is ProductManifest => Boolean(m))
const withoutEvidence = modern.filter((r) => !SEALED_EVIDENCE[r.id] && sellsProduct(r.id, r.set_id))
const hiddenModern = modern.filter((r) => !sellsProduct(r.id, r.set_id))
const hiddenWithoutEvidence = hiddenModern.filter((r) => !SEALED_EVIDENCE[r.id])
const soldModern = modern.filter((r) => sellsProduct(r.id, r.set_id))

const fmt = (n: number) => n.toLocaleString('en-US')
const md: string[] = []
md.push('# Modern sealed-product evidence')
md.push('')
md.push('Generated by `scripts/sealed-evidence-audit.ts`. The table in `server/catalog/sealed-evidence.ts` is the claim; this page compares it with the catalogue and the product manifests.')
md.push('')
md.push('## Summary')
md.push('')
md.push('| | Products |')
md.push('|---|---:|')
md.push(`| Modern rows (released 2023-01-01 or later) | ${fmt(modern.length)} |`)
md.push(`| Offered modern rows | ${fmt(soldModern.length)} |`)
md.push(`| Hidden modern rows | ${fmt(hiddenModern.length)} |`)
md.push(`| Never-shipped products removed | ${fmt(removed.length)} |`)
md.push(`| Removed products still catalogued | ${fmt(removedStillPresent.length)} |`)
md.push(`| Pull-table host rows kept | ${fmt(PULL_TABLE_HOSTS.size)} |`)
md.push(`| Rows with per-product evidence | ${fmt(audited.length)} |`)
md.push(`| Sold rows still using a generated format | ${fmt(withoutEvidence.length)} |`)
md.push(`| Hidden pull-table host rows | ${fmt(hiddenWithoutEvidence.length)} |`)
md.push(`| Evidence rows missing from the catalogue | ${missing.length} |`)
md.push(`| Count / promo mismatches | ${mismatches.length} |`)
md.push('')
md.push('## Evidence-backed products')
md.push('')
md.push('| Product | Set | Kind | Packs | Promo | Source |')
md.push('|---|---|---|---:|---|---|')
for (const m of audited.sort((a, b) => a.productId.localeCompare(b.productId))) {
  const e = SEALED_EVIDENCE[m.productId]
  md.push(`| ${m.productId} | ${m.setName} | ${m.kind} | ${e.packs} | ${e.promos.join(' or ') || '—'} | ${e.source.label} |`)
}
md.push('')
md.push('## No product without evidence')
md.push('')
if (missing.length === 0) md.push('Every evidence row resolves to a `pack_products` row.')
else {
  md.push('These evidence rows have no catalogue product:')
  md.push('')
  for (const id of missing) md.push(`- \`${id}\``)
}
md.push('')
md.push('## Counts and promos match the manifests')
md.push('')
if (mismatches.length === 0) md.push('No mismatch: every audited product reports the evidenced pack count and promo names.')
else {
  md.push('| Product | Field | Evidence | Manifest |')
  md.push('|---|---|---|---|')
  for (const x of mismatches) md.push(`| ${x.id} | ${x.field} | ${x.expected} | ${x.actual} |`)
}
md.push('')
md.push('## Products no shelf ever carried')
md.push('')
md.push('These ids are not catalogue rows. They are the generation blocklist: a fresh seed skips them and the boot prune deletes any a legacy save still holds. A row is kept only when that save owns stock of it, so the box can still be opened or sold. Three booster ids (`dc1-booster`, `dv1-booster`, `g1-booster`) are exempt from the prune as pull-table hosts for the real blisters and ETB that read their table; none is offered.')
md.push('')
if (removed.length === 0) md.push('None.')
else {
  for (const x of removed) {
    md.push(`- \`${x.id}\` is ${x.present ? 'STILL CATALOGUED' : 'removed'}: ${x.reason}`)
  }
}
md.push('')
md.push('## Sold modern rows still on the generated format')
md.push('')
if (withoutEvidence.length === 0) md.push('None: every sold modern row has a per-product evidence entry.')
else {
  md.push('These rows are not yet covered by the per-product table. They keep the generated era format, which is not a claim that the exact product shipped.')
  md.push('')
  md.push('| Product | Set | Kind | Packs |')
  md.push('|---|---|---|---:|')
  for (const r of withoutEvidence) md.push(`| ${r.id} | ${r.set_name} | ${r.kind} | ${r.packs ?? '—'} |`)
}
md.push('')
md.push('## Hidden rows with no product evidence')
md.push('')
if (hiddenWithoutEvidence.length === 0) md.push('None: no hidden row without evidence is left in the catalogue.')
else {
  md.push('These rows are kept only because the save owns stock of a product that never shipped; they are not sold, so they do not need a shelf count.')
  md.push('')
  md.push('| Product | Set | Kind | Packs | Why hidden |')
  md.push('|---|---|---|---:|---|')
  for (const r of hiddenWithoutEvidence) md.push(`| ${r.id} | ${r.set_name} | ${r.kind} | ${r.packs ?? '—'} | ${unsellableReason(r.id) ?? 'Pull-table host'} |`)
}
md.push('')
md.push('## Method')
md.push('')
md.push('Modern means a set release date on or after 2023-01-01. The evidence table names the physical pack count and any sealed promo; the manifest is rebuilt from the same database the shop reads. A missing row, a pack-count disagreement, or a promo-name disagreement is a failure in `tmp/check-sealed-evidence.ts`. Products that never existed are removed from `pack_products`, not hidden: every remaining row is either one the shop can stock or one of the three pull-table hosts listed above, and the ids in the table above are what stops them being generated again.')
md.push('')

mkdirSync('reports', { recursive: true })
writeFileSync(
  'reports/sealed-evidence.json',
  JSON.stringify(
    {
      modern: modern.length,
      sold: soldModern.length,
      hidden: hiddenModern.length,
      evidence: audited.length,
      withoutEvidence: withoutEvidence.length,
      hiddenWithoutEvidence: hiddenWithoutEvidence.length,
      missing,
      mismatches,
      removed,
      removedStillPresent: removedStillPresent.length,
      products: audited.map((m) => ({
        id: m.productId,
        set: m.setId,
        kind: m.kind,
        packs: SEALED_EVIDENCE[m.productId].packs,
        promos: SEALED_EVIDENCE[m.productId].promos,
        source: SEALED_EVIDENCE[m.productId].source,
      })),
    },
    null,
    2,
  ),
)
writeFileSync('reports/sealed-evidence.md', md.join('\n') + '\n')

console.log(`modern ${modern.length} | sold ${soldModern.length} | hidden ${hiddenModern.length} | removed ${removed.length} (${removedStillPresent.length} still present) | evidence ${audited.length} | without ${withoutEvidence.length} | missing ${missing.length} | mismatches ${mismatches.length}`)
if (missing.length) console.log('missing:', missing.join(', '))
for (const x of mismatches) console.log(`MISMATCH ${x.id} ${x.field}: expected ${x.expected}, got ${x.actual}`)
