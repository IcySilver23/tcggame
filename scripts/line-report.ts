// Line report: what the paper is, which cards wear it, and what is not claimed.
//
// Run: ./node_modules/.bin/tsx scripts/line-report.ts
//
// The claims stay apart, as every other paper report does:
//
//   identified  Bulbapedia names Line for standard Holo cards from Sword & Shield
//               through Crown Zenith and describes "thin vertical lines that refract
//               light from the top to the bottom of the Pokémon's image". That is a
//               SET-level statement: no printing record in this build claims a Line
//               card, so every row here comes from the renderer's era rule.
//   painted     a procedural reconstruction, not a scan: a ruled foil at an 8px pitch
//               with a slow top-to-bottom drift.
//   not claimed the pitch, the ridge width and the drift depth, none of which a source
//               states; and Japanese foil borders, which this English catalogue does
//               not carry.

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { holoFor } from '../src/holo'
import { printingFor } from '../src/foil/printing-db'
import { foilMaskFor } from '../src/foil/mask'
import { PATTERNS } from '../src/foil/patterns'
import { LINE_CLAIM, LINE_LIMITATION, LINE_SHEET } from '../src/foil/line-index'

const problems: string[] = []

const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare('select id, set_id, number, rarity, name from cards order by set_id, cast(number as integer)')
  .all() as { id: string; set_id: string; number: string; rarity: string | null; name: string }[]
db.close()

type Row = {
  cardId: string
  setId: string
  number: string
  name: string
  rarity: string | null
  style: string
  pattern: string | null
  mask: string | null
  maskVerified: boolean | null
}

const cards: Row[] = []
for (const row of rows) {
  const art = holoFor({ cardId: row.id, rarity: row.rarity ?? undefined })
  // A reverse printing of a Sword & Shield card carries the set's reverse paper, not
  // Line; the standard holo behind it is what this report counts. A row that resolves a
  // reverse pattern is therefore not a Line row.
  if (art?.style !== 'line' || art.pattern) continue
  const printing = printingFor({ cardId: row.id, rarity: row.rarity ?? undefined, name: row.name })
  const spec = foilMaskFor({ cardId: row.id, rarity: row.rarity ?? undefined })
  cards.push({
    cardId: row.id,
    setId: row.set_id,
    number: row.number,
    name: row.name,
    rarity: row.rarity,
    style: art.style,
    pattern: printing?.pattern ?? null,
    mask: spec?.kind ?? null,
    maskVerified: spec?.verified ?? null,
  })
}

if (!cards.length) problems.push('no card resolves to Line')
if (cards.some((c) => c.pattern !== null)) problems.push('a Line row carries a printing pattern; the report expects era-level rows only')
// A Sword & Shield card also has a reverse printing, and that copy wears the set's
// reverse paper. The card is still counted ONCE here, for its standard holo printing,
// which is what this paper paints; the reverse path is covered by the reverse report.

const setIds = [...new Set(cards.map((c) => c.setId))].sort()
const perSet = setIds.map((setId) => ({ setId, cards: cards.filter((c) => c.setId === setId) }))
if (!setIds.some((s) => s.startsWith('swsh'))) problems.push('no Sword & Shield set resolves to Line')
if (!setIds.includes('pgo')) problems.push('Pokémon GO does not resolve to Line')
if (setIds.some((s) => /^(sv|sm|me)/.test(s))) problems.push('a later or earlier era is being painted with Line')

if (PATTERNS.line.implemented !== true) problems.push('the registry does not report Line as painted')
if (PATTERNS.line.texture !== LINE_SHEET.pattern) problems.push('the registry points at a different sheet than the generated index')
if (!fs.existsSync('public' + LINE_SHEET.pattern)) problems.push('the sheet the registry points at is not shipped')

const counts = {
  claimed: cards.length,
  painted: PATTERNS.line.implemented ? cards.length : 0,
  sets: setIds.length,
  studioSets: perSet.filter((s) => s.setId.startsWith('swsh')).length,
  promoSet: perSet.find((s) => s.setId === 'pgo')?.cards.length ?? 0,
  maskVerified: cards.filter((c) => c.maskVerified).length,
  textureVerified: LINE_SHEET.textureVerified,
  coverage: LINE_SHEET.coverage,
  valley: LINE_SHEET.valley,
  ridge: LINE_SHEET.peak,
  contrast: LINE_SHEET.peak / LINE_SHEET.valley,
  seamMismatch: LINE_SHEET.seamMismatch,
  pitch: LINE_SHEET.pitch,
  stripes: LINE_SHEET.stripes,
  measuredFromCards: false,
}

const md = `# Line printings

Generated by \`scripts/line-report.ts\`.

**${LINE_CLAIM}**

## Counts

| | |
| --- | --- |
| Cards the catalogue resolves to Line | ${counts.claimed} |
| Painted (procedural ruled sheet) | ${counts.painted} |
| Sets | ${counts.sets} |
| Sword & Shield sets | ${counts.studioSets} |
| Pokémon GO | ${counts.promoSet} |
| Rows answered by a printing record | 0 — the paper is identified per SET |
| Foil area verified | ${cards.length ? counts.maskVerified : 0} of ${cards.length} |
| Texture verified against a card | ${counts.textureVerified ? 'yes' : 'no — the sheet is a drawing'} |
| Ridge pitch | ${counts.pitch}px (${counts.stripes} lines over 1024px) |
| Confirmed against real cards | no — one frame suggested ~113 lines, four gave none |
| Coverage above the mark line | ${(counts.coverage * 100).toFixed(2)}% |
| Valley / ridge | ${counts.valley.toFixed(3)} / ${counts.ridge.toFixed(3)} |
| Ridge-to-valley contrast | ${counts.contrast.toFixed(2)}× |
| Wrap step when the sheet meets itself | ${(counts.seamMismatch * 100).toFixed(2)}% |

## Per set

| Set | Cards | First examples |
| --- | --- | --- |
${perSet
  .map((s) => `| ${s.setId} | ${s.cards.length} | ${s.cards.slice(0, 4).map((c) => c.name).join(', ')}${s.cards.length > 4 ? ', …' : ''} |`)
  .join('\n')}

## What is painted, and what that claim is

\`public/foil/line/sheet.png\` is a **procedural reconstruction**: ${counts.stripes} thin vertical
ridges at a ${counts.pitch}px pitch, each ridge's brightness drifting slowly from the top of the sheet
to the bottom, over foil whose valleys stay bright (${counts.valley.toFixed(3)}) because a Line card
reads as a vertical sheen rather than as bright marks on a black field.

Three things are this build's drawing and are not sourced: the pitch, the ridge width, and how far
the drift dims a ridge. Bulbapedia names the orientation ("thin vertical lines") and the direction of
the refraction ("from the top to the bottom of the Pokémon's image"), not a line count.

It **wraps**, and the measurement is honest about what that means: the step across the two edges
that meet (${(counts.seamMismatch * 100).toFixed(2)}%) is no larger than the step between two neighbouring columns
inside the sheet, which is one pixel of a ridge's own slope rather than a phase jump. The pitch
divides the sheet and every drift is periodic in its height, so a card may sample any window.
Whether the real paper repeated is undocumented, so the wrap is this build's disclosed choice.

Copy variation is a **crop**, not a re-seed: each card id derives its own offset and a slight zoom.
A save does not distinguish physical copies, so two copies of one card id share a cut.

## Measured against real cards

\`tmp/measure-papers.py\` measures the printed spacing on a SINGLE 1080p frame, because a
frame-to-frame ratio divides one tilt by another and, under a separable foil model, divides the
printed pattern out along with the artwork. The control — this build's own 8px pitch drawn over
textured artwork — reads 0.0105 card widths against 0.0109 drawn (92 lines), and artwork with no
foil produces no peak.

Four of five frames of a Sword & Shield Supporter produce no peak at all. The fifth (a 796px card)
gives a clean 7px lag — 0.0088 card widths, about 113 lines — against the 92 drawn. That is a
single frame at a 7px period, the resolution limit of a 1080p video, so it neither confirms nor
overturns the pitch. **The 8px pitch stays this build's choice.**

## What the identification covers, and what it does not

${LINE_LIMITATION}

Two consequences follow. Every row here is an **era-level** identification: \`holo.ts\` maps the
set prefix to Line for standard holos, and no printing record claims one, so the count is how many
cards change — it is not a per-card verification. And the foil AREA is the renderer's ordinary
illustration-window default (${counts.maskVerified} of ${counts.claimed} rows carry a verified mask), because the
source describes the pattern and the border side, not which cells of the face carry it.

## Validation

\`tmp/check-line.ts\` proves: the sheet is vertical (a row varies far more than a column), repeats
exactly at its pitch, keeps its valleys bright, wraps, renders deterministically and carries no
colour; the shipped PNG and the index agree; the sampler cuts one stable window per card and
different windows per card; Sword & Shield resolves to Line while a Scarlet & Violet card resolves
to Mirage and a Sun & Moon card to Water Web, and a reverse printing keeps its own paper; the
registry reports it painted and points at the shipped file; and a render at rest is the scan byte
for byte while a tilted one adds light only inside the mask.

It does **not** confirm the sheet against a photograph: the attempt above measured real cards and
found only a single suggestive frame.
`

const report = {
  generated: 'scripts/line-report.ts',
  phase: 'Line painted',
  claims: {
    identified: LINE_CLAIM,
    limitation: LINE_LIMITATION,
    painted: 'procedural reconstruction; not a scan',
    relief: 'not claimed',
  },
  sheet: LINE_SHEET,
  counts,
  sets: perSet.map((s) => ({ setId: s.setId, cards: s.cards.length })),
  cards,
  problems,
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/line-printings.json', JSON.stringify(report, null, 2) + '\n')
fs.writeFileSync('reports/line-printings.md', md)

console.log(`Line: ${counts.claimed} cards across ${counts.sets} sets (${counts.studioSets} SWSH + PGO ${counts.promoSet}), painted ${counts.painted}`)
console.log(`  pitch ${counts.pitch}px, coverage ${(counts.coverage * 100).toFixed(2)}%, valley/ridge ${counts.valley.toFixed(3)}/${counts.ridge.toFixed(3)}, seam ${(counts.seamMismatch * 100).toFixed(2)}%`)
console.log(`  problems: ${problems.length}`)
for (const p of problems) console.log(`  - ${p}`)
if (problems.length) process.exit(1)
