// Phase 5H report: the Sun & Moon large type-symbol reverse paper.
//
// Run: ./node_modules/.bin/tsx scripts/type-symbol-large-report.ts
//
// The paper is one large symbol at the left of the card body, not a repeating
// field. The pattern is documented; the glyphs are the same stylised drawings as
// the BW/XY paper and are not official icons.

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { REVERSE_EXPANSIONS, reverseEligible } from '../src/foil/reverse-db'
import { LARGE_TYPE_SYMBOL_ASSETS, LARGE_TYPE_SYMBOL_TEXTURE_VERIFIED, LARGE_TYPE_SYMBOL_SHOWCASE } from '../src/foil/type-symbol-large-index'
import { glyphForCard } from '../src/foil/type-symbol'

const SETS = REVERSE_EXPANSIONS.filter((e) => e.pattern === 'reverse-type-symbol-large')

type Row = { set_id: string; number: string; rarity: string | null; types: string | null; supertype: string | null }
const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare(`select set_id, number, rarity, types, supertype from cards where set_id in (${SETS.map(() => '?').join(',')})`)
  .all(...SETS.map((e) => e.setId)) as Row[]
db.close()

const eligible = rows.filter((r) => reverseEligible({ setId: r.set_id, number: r.number, rarity: r.rarity }))
const usable = eligible.filter((r) => glyphForCard({ types: r.types, supertype: r.supertype }) !== null)

const problems: string[] = []
for (const e of SETS) {
  if (e.mask !== 'outside-art') problems.push(`${e.setId}: mask is ${e.mask}, expected the card body`)
  if (!e.implemented) problems.push(`${e.setId}: not marked validated`)
}
for (const [id, a] of Object.entries(LARGE_TYPE_SYMBOL_ASSETS)) {
  if (!fs.existsSync('public' + a.texture)) problems.push(`${id}: texture not shipped`)
}

const counts = {
  expansions: SETS.length,
  validated: SETS.filter((e) => e.implemented).length,
  glyphs: Object.keys(LARGE_TYPE_SYMBOL_ASSETS).length,
  reversePrintings: eligible.length,
  printingsWithKnownType: usable.length,
  textureVerified: LARGE_TYPE_SYMBOL_TEXTURE_VERIFIED,
  showcase: LARGE_TYPE_SYMBOL_SHOWCASE.length,
}

const report = {
  generated: 'scripts/type-symbol-large-report.ts',
  phase: 'Phase 5H — Sun & Moon large type-symbol paper',
  counts,
  expansions: SETS.map((e) => ({ setId: e.setId, name: e.name, year: e.year, mask: e.mask, implemented: e.implemented })),
  glyphs: Object.entries(LARGE_TYPE_SYMBOL_ASSETS).map(([id, a]) => ({
    id, label: a.label, texture: a.texture, coverage: a.coverage, peak: a.peak, centerU: a.centerU, centerV: a.centerV,
  })),
  problems,
  honesty: [
    'Bulbapedia describes a large type symbol (Poké Ball for Trainers) on the left of the card body for this run. That identifies the paper, not its artwork.',
    'The glyphs are the same stylised geometric drawings used for the BW/XY paper, not official icons, and none is verified against a photograph.',
    'The symbol is one large mark at the left, not a repeating field; the sampler anchors an aspect-correct window around it and leaves the rest of the body unmarked plain foil.',
    'The type comes from the card; an unknown type renders plain foil rather than the wrong symbol.',
    `Of ${eligible.length} reverse printings here, ${usable.length} have a usable type; the rest show plain foil.`,
  ],
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/type-symbol-large-printings.json', JSON.stringify(report, null, 2) + '\n')
const lines = [
  '# Sun & Moon large type-symbol paper',
  '',
  `Generated by \`${report.generated}\`. Phase 5H of \`HOLOFOIL_ROADMAP.md\`.`,
  '',
  '## Numbers',
  '',
  `- Expansions on this paper: **${counts.expansions}** (${counts.validated} validated).`,
  `- Reverse printings: **${counts.reversePrintings}**; usable type: ${counts.printingsWithKnownType}.`,
  `- Glyph sheets: **${counts.glyphs}**; texture verified: ${counts.textureVerified ? 'yes' : 'no — stylised reconstruction'}.`,
  '',
  '## What is verified and what is drawn',
  '',
  ...report.honesty.map((h) => `- ${h}`),
  '',
  '## Expansions',
  '',
  '| set | name | mask | validated |',
  '| --- | --- | --- | --- |',
  ...report.expansions.map((e) => `| \`${e.setId}\` | ${e.name} | ${e.mask === 'outside-art' ? 'body' : 'window'} | ${e.implemented ? 'yes' : 'no'} |`),
  '',
]
if (problems.length) {
  lines.push('## Problems', '', ...problems.map((p) => `- ${p}`), '')
}
fs.writeFileSync('reports/type-symbol-large-printings.md', lines.join('\n'))

console.log(`expansions: ${counts.expansions} (${counts.validated}) · printings: ${counts.reversePrintings} · usable type: ${counts.printingsWithKnownType}`)
console.log('written: reports/type-symbol-large-printings.json, reports/type-symbol-large-printings.md')
if (problems.length) { for (const p of problems) console.log(' -', p); process.exitCode = 1 }
else console.log('all 13 expansions use the body mask and are validated')
