import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import Database from 'better-sqlite3'
import { GLYPH_IDS, GLYPH_LABEL } from '../src/foil/type-glyph'
import { renderReverseTileIntricateSheet, REVERSE_TILE_INTRICATE_SIZE } from '../src/foil/reverse-tile-intricate-sheet'

const OUT_DIR = 'public/foil/reverse/tile-intricate'
const INDEX_FILE = 'src/foil/reverse-tile-intricate-index.ts'
const DB_FILE = 'data/tcglife.db'

const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()
function crc32(buf: Buffer): number {
  let c = 0xffffffff
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 255] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body), 0)
  return Buffer.concat([len, body, crc])
}
function encodePng(w: number, h: number, rgba: Uint8ClampedArray): Buffer {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6
  const stride = w * 4
  const raw = Buffer.alloc((stride + 1) * h)
  for (let y = 0; y < h; y++) {
    raw[y * (stride + 1)] = 0
    Buffer.from(rgba.buffer, rgba.byteOffset + y * stride, stride).copy(raw, y * (stride + 1) + 1)
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0)),
  ])
}

const problems: string[] = []
fs.mkdirSync(OUT_DIR, { recursive: true })
type Measured = { id: string; label: string; texture: string; coverage: number; peak: number; seam: number }
const measured: Measured[] = []
for (const glyph of GLYPH_IDS) {
  const sheet = renderReverseTileIntricateSheet(glyph, REVERSE_TILE_INTRICATE_SIZE)
  fs.writeFileSync(path.join(OUT_DIR, `${glyph}.png`), encodePng(sheet.size, sheet.size, sheet.rgba))
  if (sheet.coverage < 0.2 || sheet.coverage > 0.95) problems.push(`${glyph}: coverage ${(sheet.coverage * 100).toFixed(1)}%`)
  if (sheet.peak < 0.9) problems.push(`${glyph}: peak ${sheet.peak.toFixed(2)} too dim`)
  if (sheet.seam > 0.05) problems.push(`${glyph}: seam ${sheet.seam.toFixed(4)} too high to tile`)
  measured.push({
    id: glyph, label: GLYPH_LABEL[glyph], texture: `/foil/reverse/tile-intricate/${glyph}.png`,
    coverage: Number(sheet.coverage.toFixed(4)), peak: Number(sheet.peak.toFixed(4)), seam: Number(sheet.seam.toFixed(5)),
  })
}

type Showcase = { cardId: string; setId: string; number: string; name: string; rarity: string; types: string | null; supertype: string | null; variant: string }
const showcase: Showcase[] = []
if (fs.existsSync(DB_FILE)) {
  const db = new Database(DB_FILE, { readonly: true })
  const rows = db.prepare("select id, set_id, number, name, rarity, types, supertype from cards where id in ('sv1-1','sv1-2')").all() as
    { id: string; set_id: string; number: string; name: string; rarity: string | null; types: string | null; supertype: string | null }[]
  db.close()
  for (const r of rows) showcase.push({
    cardId: r.id, setId: r.set_id, number: r.number, name: r.name, rarity: r.rarity ?? '',
    types: r.types, supertype: r.supertype, variant: 'reverseHolofoil',
  })
} else problems.push('card database missing')

const entries = measured.map((m) => `  ${m.id}: { id: ${JSON.stringify(m.id)}, label: ${JSON.stringify(m.label)}, texture: ${JSON.stringify(m.texture)}, coverage: ${m.coverage}, peak: ${m.peak}, seam: ${m.seam} },`).join('\n')

const index = `// GENERATED by scripts/reverse-tile-intricate-foil.ts — do not hand-edit.
//
// Scarlet & Violet reverse paper: nested rounded tiles carrying the card's own
// type symbol at more than one size (Poké Ball for Trainers). Sheets tile, so a
// card samples any window.
//
// PROCEDURAL RECONSTRUCTION: the paper's identity is documented, the artwork is
// not. No factory scan was available; every field carries verified: false.

import type { GlyphId } from './type-glyph'

export type ReverseTileIntricateAsset = {
  id: GlyphId
  label: string
  texture: string
  coverage: number
  peak: number
  seam: number
}

export const REVERSE_TILE_INTRICATE_ASSETS: Record<GlyphId, ReverseTileIntricateAsset> = {
${entries}
}

/** Copies across the card at 1x. */
export const REVERSE_TILE_INTRICATE_SCALE = 1.05
export const REVERSE_TILE_INTRICATE_TEXTURE_VERIFIED = false
export const REVERSE_TILE_INTRICATE_NOTE =
  'Nested tiles carrying the card\\'s type symbol at more than one size; a stylised reconstruction of the Scarlet & Violet reverse paper, not official icon artwork.'

export const REVERSE_TILE_INTRICATE_SHOWCASE: {
  cardId: string; setId: string; number: string; name: string; rarity: string
  types: string | null; supertype: string | null; variant: string
}[] = ${JSON.stringify(showcase, null, 2)}
`
fs.writeFileSync(INDEX_FILE, index)
console.log(`${measured.length} intricate tile sheets → ${OUT_DIR}`)
console.log(measured.map((m) => `${m.id}: ${(m.coverage * 100).toFixed(1)}% peak ${m.peak.toFixed(2)} seam ${m.seam.toFixed(4)}`).join('\n'))
console.log(`index: ${INDEX_FILE} (${showcase.length} showcase cards)`)
if (problems.length) {
  console.log(`PROBLEMS (${problems.length}):`)
  for (const p of problems) console.log(' -', p)
  process.exitCode = 1
} else console.log('every intricate tile sheet passes its gates')
