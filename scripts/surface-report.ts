// Phase 11 report: textured printings and the surface they would wear.
//
// Two reliefs ship and the era decides which one: Black & White and XY full arts
// are described as heavy with deeply etched texture, while later eras are finer.
// Run: ./node_modules/.bin/tsx scripts/surface-report.ts

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { SURFACE_TEXTURES, surfaceFor, TEXTURED_SURFACE_VERIFIED } from '../src/foil/surface-textures'

const db = new Database('data/tcglife.db', { readonly: true })
const rows = db.prepare('select set_id, number, rarity from cards where rarity is not null').all() as
  { set_id: string; number: string; rarity: string }[]
db.close()

type Row = { rarity: string; cards: number; surface: string }
const byRarity = new Map<string, Row>()
const bySurface: Record<string, number> = {}
for (const id of Object.keys(SURFACE_TEXTURES)) bySurface[id] = 0

for (const row of rows) {
  const surface = surfaceFor({ rarity: row.rarity, cardId: `${row.set_id}-${row.number}` })
  if (!surface) continue
  bySurface[surface] = (bySurface[surface] ?? 0) + 1
  const hit = byRarity.get(row.rarity) ?? { rarity: row.rarity, cards: 0, surface }
  hit.cards++
  byRarity.set(row.rarity, hit)
}

const textured = [...byRarity.values()].sort((a, b) => b.cards - a.cards)

const problems: string[] = []
for (const [id, meta] of Object.entries(SURFACE_TEXTURES)) {
  if (!fs.existsSync('public' + meta.texture)) problems.push(`${id}: ${meta.texture} not shipped`)
  if (meta.verified) problems.push(`${id}: marked verified without a reference`)
}
if (!textured.length) problems.push('no rarity resolves to a textured surface')
if ((bySurface['etched-deep'] ?? 0) === 0) problems.push('no card routes to the deep etched relief')

const report = {
  generated: 'scripts/surface-report.ts',
  phase: 'Phase 11 — normal maps and textured printings',
  counts: {
    surfaces: Object.keys(SURFACE_TEXTURES).length,
    rarities: textured.length,
    cards: Object.values(bySurface).reduce((n, v) => n + v, 0),
    cardsBySurface: bySurface,
    textureVerified: TEXTURED_SURFACE_VERIFIED,
  },
  eraRule: {
    'etched-deep': 'Black & White and XY full arts (set ids bw*, xy*, g1*, dc*)',
    etched: 'Sun & Moon, Sword & Shield and Scarlet & Violet tiers, and any era not named',
    sparkle: 'The four Shiny Vault rarities (Rare Shiny, Rare Shiny GX, Shiny Rare, Shiny Ultra Rare)',
  },
  surfaces: Object.values(SURFACE_TEXTURES).map((s) => ({
    id: s.id, label: s.label, texture: s.texture, strength: s.strength,
    verified: s.verified, modelled: s.modelled, note: s.note, source: s.source,
  })),
  rarities: textured,
  problems,
  honesty: [
    'Both reliefs are procedural lattices, not scans of a textured card; every surface records verified: false and modelled: true.',
    'What is sourced is the weight: Black & White and XY full arts are described as heavy with deeply etched texture, later full arts as lighter and finer. The exact spacing, depth and slope are this build\'s model.',
    'Scarlet & Violet textures are in reality art-specific. Using one fine relief across that era is a disclosed simplification, not a claim about any individual card.',
    'The rarity list is this build\'s model of which tiers are etched. A tier not listed renders smooth foil rather than borrowing a relief.',
    'Shiny Vault tiers are routed to their own granular `sparkle` relief: the sources call that finish embossed, etched and textured, which is relief, and the macro photographs show a dense shimmer with no periodic repeat, so a grain is drawn rather than a lattice. The grain\'s scale and depth are modelled, and a correlation-length test against the same photographs (`reports/shiny-grain.md`) finds no attributable density; the density is accepted as final in that report (its Decision section), so the drawn periods are a decision rather than a pending measurement; the paper stays unnamed upstream and no sheet is borrowed. Paldean Fates also documents a silver border, which is not modelled.',
    'The surface only shades pixels its own coverage mask allows; it never writes alpha and never changes where foil is. For a textured full art that mask is the foil mask. A modern ball reverse is the deliberate exception: its etch uses a full-card mask while the ball foil stays outside the art, so the etch can cross the picture without putting the stamp there.',
  ],
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/surface-printings.json', JSON.stringify(report, null, 2) + '\n')

const lines = [
  '# Textured printings and their surface',
  '',
  `Generated by \`${report.generated}\`. Phase 11 of \`HOLOFOIL_ROADMAP.md\`.`,
  '',
  '## Numbers',
  '',
  `- Surfaces shipped: **${report.counts.surfaces}**; texture verified: ${report.counts.textureVerified ? 'yes' : 'no — modelled relief'}.`,
  `- Rarities routed: **${report.counts.rarities}**; cards in the catalogue: **${report.counts.cards}**.`,
  `- Deep etched (BW/XY): **${report.counts.cardsBySurface['etched-deep']}**; fine etched (later eras): **${report.counts.cardsBySurface['etched']}**.`,
  '',
  '## Era rule',
  '',
  '| surface | eras |',
  '| --- | --- |',
  ...Object.entries(report.eraRule).map(([s, eras]) => `| ${s} | ${eras} |`),
  '',
  '## Surfaces',
  '',
  '| surface | strength | verified | source |',
  '| --- | --- | --- | --- |',
  ...report.surfaces.map((s) => `| ${s.id} — ${s.label} | ${s.strength} | ${s.verified ? 'yes' : 'no — modelled'} | ${s.source} |`),
  '',
  '## What is sourced and what is drawn',
  '',
  ...report.honesty.map((h) => `- ${h}`),
  '',
  '## Rarities',
  '',
  '| rarity | cards | surface |',
  '| --- | --- | --- |',
  ...textured.map((r) => `| ${r.rarity} | ${r.cards} | ${r.surface} |`),
  '',
]
if (problems.length) lines.push('## Problems', '', ...problems.map((p) => `- ${p}`), '')
fs.writeFileSync('reports/surface-printings.md', lines.join('\n'))

console.log(`surfaces: ${report.counts.surfaces} · rarities: ${report.counts.rarities} · cards: ${report.counts.cards}`)
console.log(`deep etched: ${report.counts.cardsBySurface['etched-deep']} · fine etched: ${report.counts.cardsBySurface['etched']}`)
console.log('written: reports/surface-printings.json, reports/surface-printings.md')
if (problems.length) { for (const p of problems) console.log(' -', p); process.exitCode = 1 }
else console.log('every textured rarity resolves to a shipped, modelled surface')
