// Cracked Ice sheet → shipped texture + generated index.
//
// Run: ./node_modules/.bin/tsx scripts/crackedice-foil.ts
//
// No Cracked Ice scan, photograph or tilt video exists in this repository, so the
// sheet is DRAWN from Bulbapedia's description ("irregular reflective shapes
// resembling pieces of cracked or shattered glass") and the index records that it
// is a reconstruction. The crash of terms matters: the PATTERN identification is
// verified for Frost Rotom, the TEXTURE is not.
//
// The script measures the sheet rather than trusting it:
//   - coverage and peak, so a blank or flat sheet fails here;
//   - seam ratio across the wrap, to confirm the sheet is genuinely tileable;
//   - facet count, so the fracture keeps its vocabulary.
//
// It also writes the showcase card from the catalog: Rising Rivals Frost Rotom,
// the printing Bulbapedia explicitly describes.

import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import Database from 'better-sqlite3'
import {
  renderCrackedIceSheet,
  CRACKEDICE_CELLS,
  CRACKEDICE_SEED,
  CRACKEDICE_SHEET_SIZE,
} from '../src/foil/crackedice-sheet'

const OUT_DIR = 'public/foil/crackedice'
const OUT_FILE = path.join(OUT_DIR, 'sheet.png')
const INDEX_FILE = 'src/foil/crackedice-index.ts'
const DB_FILE = 'data/tcglife.db'

const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()

function crc32(buf: Buffer): number {
  let c = 0xffffffff
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 255] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body), 0)
  return Buffer.concat([len, body, crc])
}

function encodePng(w: number, h: number, rgba: Uint8ClampedArray): Buffer {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0)
  ihdr.writeUInt32BE(h, 4)
  ihdr[8] = 8
  ihdr[9] = 6
  const stride = w * 4
  const raw = Buffer.alloc((stride + 1) * h)
  for (let y = 0; y < h; y++) {
    raw[y * (stride + 1)] = 0
    Buffer.from(rgba.buffer, rgba.byteOffset + y * stride, stride).copy(raw, y * (stride + 1) + 1)
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ])
}

const problems: string[] = []
const sheet = renderCrackedIceSheet(CRACKEDICE_SHEET_SIZE, CRACKEDICE_SEED)

if (sheet.coverage < 0.9) problems.push(`coverage ${(sheet.coverage * 100).toFixed(1)}% should be near-complete: every shard is foil, only the brightness differs`)
if (sheet.peak < 0.8) problems.push(`peak ${sheet.peak.toFixed(3)}: the cracks are too dim to read as glints`)
if (sheet.seamRatio > 2) problems.push(`seam ratio ${sheet.seamRatio.toFixed(2)}: the sheet is meant to tile, but the wrap is discontinuous`)
if (sheet.seeds.length !== CRACKEDICE_CELLS * CRACKEDICE_CELLS) problems.push('facet count does not match the fracture grid')

fs.mkdirSync(OUT_DIR, { recursive: true })
fs.writeFileSync(OUT_FILE, encodePng(sheet.size, sheet.size, sheet.rgba))

type Showcase = { cardId: string; setId: string; number: string; name: string; rarity: string }
const showcase: Showcase[] = []
if (fs.existsSync(DB_FILE)) {
  const db = new Database(DB_FILE, { readonly: true })
  const row = db
    .prepare("select id, set_id, number, name, rarity from cards where id = 'pl2-RT2'")
    .get() as { id: string; set_id: string; number: string; name: string; rarity: string | null } | undefined
  db.close()
  if (!row) problems.push('pl2-RT2 (Frost Rotom) is not in the catalog')
  else showcase.push({ cardId: row.id, setId: row.set_id, number: row.number, name: row.name, rarity: row.rarity ?? '' })
} else {
  problems.push('card database missing: cannot choose the showcase card')
}

const index = `// GENERATED by scripts/crackedice-foil.ts — do not hand-edit.
//
// No Cracked Ice factory sheet, photograph or tilt video exists in this repository.
// This texture is a PROCEDURAL RECONSTRUCTION of Bulbapedia's description:
// "irregular reflective shapes resembling pieces of cracked or shattered glass".
// It is a drawing of the pattern, not a scan, and the renderer reports it as such.
//
// The fracture is a Voronoi sheet cut with toroidal distances, so it tiles: cards
// sample any window and the cracks continue across the wrap (measured seam ratio
// ${sheet.seamRatio.toFixed(3)}, where 1.0 means the wrap looks like any interior seam).
//
// Measured from the shipped file:
//   coverage ${(sheet.coverage * 100).toFixed(2)}% of texels carry ink (alpha > 0.1)
//   peak     ${sheet.peak.toFixed(3)} alpha at a crack
//   facets   ${sheet.seeds.length} (${CRACKEDICE_CELLS}x${CRACKEDICE_CELLS} jittered seeds)
//
// Which CARD wears this is a separate claim in printing-db.ts, and it is much
// narrower than the pattern's reputation: only Frost Rotom (Rising Rivals RT2) is
// named by a source read here.

export type CrackedIceSheetInfo = {
  texture: string
  size: string
  seed: number
  facets: number
  coverage: number
  peak: number
  seamRatio: number
  /** Voronoi cracks with toroidal distances: a card may sample any window. */
  tileable: true
  /** Procedural drawing, not a scan. */
  concept: true
  /** No printing is verified against this texture. */
  textureVerified: false
  note: string
}

export const CRACKEDICE_SHEET: CrackedIceSheetInfo = {
  texture: '/foil/crackedice/sheet.png',
  size: '${sheet.size}x${sheet.size}',
  seed: ${sheet.seed},
  facets: ${sheet.seeds.length},
  coverage: ${sheet.coverage.toFixed(5)},
  peak: ${sheet.peak.toFixed(5)},
  seamRatio: ${sheet.seamRatio.toFixed(4)},
  tileable: true,
  concept: true,
  textureVerified: false,
  note: 'Procedural Voronoi fracture: flat facets of differing reflectivity separated by thin bright cracks. Drawn from Bulbapedia\\'s description; not a scan.',
}

/** The sheet repeats across the card at this many copies per card width. */
export const CRACKEDICE_SCALE = 1.15

/** Cards the inspector and report open first. */
export const CRACKEDICE_SHOWCASE: { cardId: string; setId: string; number: string; name: string; rarity: string }[] = ${JSON.stringify(showcase, null, 2)}
`

fs.writeFileSync(INDEX_FILE, index)

console.log(`sheet: ${sheet.size}x${sheet.size} → ${OUT_FILE}`)
console.log(`coverage ${(sheet.coverage * 100).toFixed(2)}% · peak ${sheet.peak.toFixed(3)} · seam ratio ${sheet.seamRatio.toFixed(3)}`)
console.log(`facets: ${sheet.seeds.length}`)
console.log(`index: ${INDEX_FILE} (${showcase.length} showcase cards)`)
if (problems.length) {
  console.log(`PROBLEMS (${problems.length}):`)
  for (const p of problems) console.log(' -', p)
  process.exitCode = 1
} else {
  console.log('sheet passes its own gates')
}
