// Builds the δ Delta Species index from the catalogue.
//
// Run: ./node_modules/.bin/tsx scripts/delta-species-index.ts
//
// The roadmap carried one honesty note for years: "δ Delta Species undetectable from
// the card row, so those holos still get Cosmos." The card row DOES record the marker —
// δ is part of the printed name, and the catalogue copies names — so this was a missing
// query, not missing evidence. This script answers the query and writes the index the
// printing database reads:
//
//   src/foil/delta-species-index.ts   the δ-marked Holo RARE cards of the four Delta-era
//                                     expansions, by card id, generated from data/tcglife.db
//
// Why a generated file rather than a name check at render time: the renderer only has a
// card id, rarity and variant — the name is not threaded through every card component —
// and a list derived from the catalogue keeps the answer identical everywhere the card
// is drawn. Why generated rather than hand-listed: a catalogue change must not be able to
// leave a card behind, and tmp/check-delta-species.ts re-derives the list and fails when
// the committed file and the database disagree.
//
// Deliberately NOT included:
//   - Rare Holo EX and Gold Star δ cards: different treatments, not the plain holo paper;
//   - POP4's Deoxys δ: the one δ card Bulbapedia gives the cosmic design, a promo from a
//     different product that already has its own Cosmos row in printing-db.ts.

import fs from 'node:fs'
import Database from 'better-sqlite3'

export const DELTA_SPECIES_SETS = ['ex11', 'ex13', 'ex14', 'ex15'] as const
const OUT = 'src/foil/delta-species-index.ts'

type Row = { id: string; set_id: string; number: string; name: string }

const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare(
    `SELECT id, set_id, number, name FROM cards
     WHERE set_id IN (${DELTA_SPECIES_SETS.map(() => '?').join(',')})
       AND rarity = 'Rare Holo'
       AND name LIKE '%δ%'
     ORDER BY set_id, CAST(number AS INTEGER)`,
  )
  .all(...DELTA_SPECIES_SETS) as Row[]
db.close()

const problems: string[] = []
if (rows.length === 0) {
  problems.push('no δ holo rares found — the name marker or the set list changed')
}

const bySet: Record<string, number> = {}
for (const r of rows) bySet[r.set_id] = (bySet[r.set_id] ?? 0) + 1

const entry = (r: Row): string =>
  `  { cardId: ${JSON.stringify(r.id)}, setId: ${JSON.stringify(r.set_id)}, number: ${JSON.stringify(r.number)}, name: ${JSON.stringify(r.name)} },`

const file = `// GENERATED by scripts/delta-species-index.ts — do not hand-edit.
//
// The δ Delta Species holo rares: ${rows.length} cards across ${Object.keys(bySet).length} expansions
// (${Object.entries(bySet)
  .map(([set, n]) => `${set} ${n}`)
  .join(', ')}).
//
// Read by src/foil/printing-db.ts, which resolves each to the \`plain-holo\` paper:
// Bulbapedia gives these holos a plain foil treatment rather than the era's Cosmos
// sheet. The list exists because the card row carries the δ marker only in its NAME,
// which the renderer does not receive — so the marker is resolved once, here, from the
// catalogue, instead of being guessed from rarity or set.
//
// Not included on purpose: Rare Holo EX and Gold Star δ cards (different treatments),
// and POP4's Deoxys δ (the one δ card given the cosmic design; it has its own Cosmos
// row as a promo printing).

export const DELTA_SPECIES_SETS = ${JSON.stringify(DELTA_SPECIES_SETS)} as const

export type DeltaSpeciesHoloRare = { cardId: string; setId: string; number: string; name: string }

export const DELTA_SPECIES_HOLO_RARES: DeltaSpeciesHoloRare[] = [
${rows.map(entry).join('\n')}
]

export const DELTA_SPECIES_COUNTS = {
  total: ${rows.length},
  bySet: ${JSON.stringify(bySet)},
  generatedFrom: 'data/tcglife.db',
} as const

export const DELTA_SPECIES_SOURCE = 'https://bulbapedia.bulbagarden.net/wiki/Holofoil_(TCG)'

export const DELTA_SPECIES_NOTE =
  'δ Delta Species holo rares were printed on a plain foil rather than the era’s Cosmos paper. The card row records the marker in its name, and this generated index is that answer; the one δ card given the cosmic design is POP4’s Deoxys δ, a promo whose own row names Cosmos.'
`

fs.writeFileSync(OUT, file)
console.log(
  `delta-species-index: ${rows.length} δ holo rares (${Object.entries(bySet)
    .map(([s, n]) => `${s} ${n}`)
    .join(', ')}) → ${OUT}`,
)
if (problems.length > 0) {
  console.error(problems.map((p) => `FAIL ${p}`).join('\n'))
  process.exit(1)
}
