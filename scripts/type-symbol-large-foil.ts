// Sun & Moon large type-symbol paper → shipped sheets + generated index.
//
// Run: ./node_modules/.bin/tsx scripts/type-symbol-large-foil.ts
//
// Bulbapedia: "A large type symbol (Poké Ball for Trainers) on the left of the
// card body." So this paper is ONE large glyph at the left, sampled in an
// aspect-correct window, not a repeating field. The glyphs are the same stylised
// drawings as the BW/XY paper and are not official icons; the index says so.

import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import Database from 'better-sqlite3'
import {
  GLYPH_IDS, GLYPH_LABEL, renderLargeTypeSymbolSheet, TYPE_SYMBOL_SEED,
  TYPE_SYMBOL_LARGE_SIZE, type GlyphId,
} from '../src/foil/type-glyph'

const OUT_DIR = 'public/foil/type-symbol'
const INDEX_FILE = 'src/foil/type-symbol-large-index.ts'
const DB_FILE = 'data/tcglife.db'

const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()
function crc32(buf: Buffer): number {
  let c = 0xffffffff
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 255] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body), 0)
  return Buffer.concat([len, body, crc])
}
function encodePng(w: number, h: number, rgba: Uint8ClampedArray): Buffer {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6
  const stride = w * 4
  const raw = Buffer.alloc((stride + 1) * h)
  for (let y = 0; y < h; y++) {
    raw[y * (stride + 1)] = 0
    Buffer.from(rgba.buffer, rgba.byteOffset + y * stride, stride).copy(raw, y * (stride + 1) + 1)
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0)),
  ])
}

const problems: string[] = []
fs.mkdirSync(OUT_DIR, { recursive: true })
type Measured = { id: GlyphId; label: string; texture: string; coverage: number; peak: number; centerU: number; centerV: number }
const measured: Measured[] = []
for (const glyph of GLYPH_IDS) {
  const sheet = renderLargeTypeSymbolSheet(glyph, TYPE_SYMBOL_LARGE_SIZE, TYPE_SYMBOL_SEED)
  if (sheet.coverage < 0.008 || sheet.coverage > 0.12) problems.push(`${glyph}: coverage ${(sheet.coverage * 100).toFixed(2)}% is wrong for one large symbol`)
  if (sheet.peak < 0.8) problems.push(`${glyph}: peak ${sheet.peak.toFixed(2)} too dim`)
  const file = path.join(OUT_DIR, `large-${glyph}.png`)
  fs.writeFileSync(file, encodePng(sheet.size, sheet.size, sheet.rgba))
  measured.push({
    id: glyph, label: GLYPH_LABEL[glyph], texture: `/foil/type-symbol/large-${glyph}.png`,
    coverage: Number(sheet.coverage.toFixed(5)), peak: Number(sheet.peak.toFixed(5)),
    centerU: Number(sheet.centerU.toFixed(4)), centerV: Number(sheet.centerV.toFixed(4)),
  })
}

type Showcase = { cardId: string; setId: string; number: string; name: string; rarity: string; types: string | null; supertype: string | null; variant: string }
const showcase: Showcase[] = []
if (fs.existsSync(DB_FILE)) {
  const db = new Database(DB_FILE, { readonly: true })
  const rows = db.prepare("select id, set_id, number, name, rarity, types, supertype from cards where id in ('sm1-1','det1-1')").all() as
    { id: string; set_id: string; number: string; name: string; rarity: string | null; types: string | null; supertype: string | null }[]
  db.close()
  for (const r of rows) showcase.push({
    cardId: r.id, setId: r.set_id, number: r.number, name: r.name, rarity: r.rarity ?? '',
    types: r.types, supertype: r.supertype, variant: 'reverseHolofoil',
  })
} else problems.push('card database missing')

const entries = measured.map((m) => `  ${m.id}: { id: ${JSON.stringify(m.id)}, label: ${JSON.stringify(m.label)}, texture: ${JSON.stringify(m.texture)}, coverage: ${m.coverage}, peak: ${m.peak}, centerU: ${m.centerU}, centerV: ${m.centerV} },`).join('\n')

const index = `// GENERATED by scripts/type-symbol-large-foil.ts — do not hand-edit.
//
// The Sun & Moon reverse paper puts ONE LARGE TYPE SYMBOL on the left of the card
// body (a Poké Ball for Trainers). Each sheet here holds one glyph at the left;
// the sampler maps an aspect-correct window around it, with no tiling.
//
// The glyphs are stylised geometric drawings, not official icons, and no sheet is
// verified against a photograph.

export type LargeTypeSymbolGlyph =
  | 'grass' | 'fire' | 'water' | 'lightning' | 'psychic' | 'fighting'
  | 'darkness' | 'metal' | 'dragon' | 'fairy' | 'colorless' | 'trainer'

export type LargeTypeSymbolAsset = {
  id: LargeTypeSymbolGlyph
  label: string
  texture: string
  coverage: number
  peak: number
  /** Symbol centre in sheet space, used to anchor the card window. */
  centerU: number
  centerV: number
}

export const LARGE_TYPE_SYMBOL_ASSETS: Record<LargeTypeSymbolGlyph, LargeTypeSymbolAsset> = {
${entries}
}

export const LARGE_TYPE_SYMBOL_TEXTURE_VERIFIED = false
export const LARGE_TYPE_SYMBOL_NOTE =
  'One large stylised type glyph at the left of the card body; a reconstruction of the Sun & Moon reverse paper, not official icon artwork.'

export const LARGE_TYPE_SYMBOL_SHOWCASE: {
  cardId: string; setId: string; number: string; name: string; rarity: string
  types: string | null; supertype: string | null; variant: string
}[] = ${JSON.stringify(showcase, null, 2)}
`
fs.writeFileSync(INDEX_FILE, index)
console.log(`${measured.length} large glyph sheets → ${OUT_DIR}`)
console.log(measured.map((m) => `${m.id}: ${(m.coverage * 100).toFixed(2)}% peak ${m.peak.toFixed(2)} at ${m.centerU.toFixed(2)},${m.centerV.toFixed(2)}`).join('\n'))
console.log(`index: ${INDEX_FILE} (${showcase.length} showcase cards)`)
if (problems.length) {
  console.log(`PROBLEMS (${problems.length}):`)
  for (const p of problems) console.log(' -', p)
  process.exitCode = 1
} else console.log('every large glyph sheet passes its gates')
