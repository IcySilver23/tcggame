// Phase 5F report: the BW/XY type-symbol reverse paper.
//
// Run: ./node_modules/.bin/tsx scripts/type-symbol-report.ts
//
// Two claims, kept apart:
//   - the PATTERN is documented: Bulbapedia describes the card's type symbol in
//     the card body for this run, with a Poké Ball for Trainers, and the expansion
//     table carries it for 24 English sets;
//   - the ARTWORK is a reconstruction: twelve stylised glyphs drawn here, not the
//     official icons, and not verified against a card.
//
// It also counts how many reverse printings the pattern covers in this catalogue,
// and how many of those cards carry a type the loader can act on.

import fs from 'node:fs'
import Database from 'better-sqlite3'
import { REVERSE_EXPANSIONS, reverseEligible } from '../src/foil/reverse-db'
import { TYPE_SYMBOL_ASSETS, TYPE_SYMBOL_TEXTURE_VERIFIED, TYPE_SYMBOL_SHOWCASE } from '../src/foil/type-symbol-index'
import { glyphForCard } from '../src/foil/type-symbol'

const TYPE_SYMBOL_SETS = REVERSE_EXPANSIONS.filter((e) => e.pattern === 'reverse-type-symbol')

type Row = { set_id: string; number: string; rarity: string | null; types: string | null; supertype: string | null }
const db = new Database('data/tcglife.db', { readonly: true })
const rows = db
  .prepare(
    `select set_id, number, rarity, types, supertype from cards where set_id in (${TYPE_SYMBOL_SETS.map(() => '?').join(',')})`,
  )
  .all(...TYPE_SYMBOL_SETS.map((e) => e.setId)) as Row[]
db.close()

const eligible = rows.filter((r) =>
  reverseEligible({ setId: r.set_id, number: r.number, rarity: r.rarity }),
)
const knownGlyph = eligible.filter((r) => glyphForCard({ types: r.types, supertype: r.supertype }) !== null)

const counts = {
  expansions: TYPE_SYMBOL_SETS.length,
  validated: TYPE_SYMBOL_SETS.filter((e) => e.implemented).length,
  glyphs: Object.keys(TYPE_SYMBOL_ASSETS).length,
  reversePrintings: eligible.length,
  printingsWithKnownType: knownGlyph.length,
  printingsWithoutType: eligible.length - knownGlyph.length,
  textureVerified: TYPE_SYMBOL_TEXTURE_VERIFIED,
  showcase: TYPE_SYMBOL_SHOWCASE.length,
}

const problems: string[] = []
for (const e of TYPE_SYMBOL_SETS) {
  if (e.pattern !== 'reverse-type-symbol') problems.push(`${e.setId}: wrong pattern`)
  if (e.mask !== 'outside-art') problems.push(`${e.setId}: mask is ${e.mask}, expected the card body`)
  if (!e.implemented) problems.push(`${e.setId}: not marked validated`)
}
for (const [id, a] of Object.entries(TYPE_SYMBOL_ASSETS)) {
  if (!fs.existsSync('public' + a.texture)) problems.push(`${id}: texture ${a.texture} is not shipped`)
}

const report = {
  generated: 'scripts/type-symbol-report.ts',
  phase: 'Phase 5F — BW/XY type-symbol reverse paper',
  counts,
  expansions: TYPE_SYMBOL_SETS.map((e) => ({
    setId: e.setId,
    name: e.name,
    year: e.year,
    mask: e.mask,
    status: e.status,
    implemented: e.implemented,
    source: e.source,
  })),
  glyphs: Object.entries(TYPE_SYMBOL_ASSETS).map(([id, a]) => ({
    id, label: a.label, texture: a.texture, coverage: a.coverage, peak: a.peak, seamRatio: a.seamRatio,
  })),
  problems,
  honesty: [
    'The pattern is identified, not the artwork: Bulbapedia describes the card’s type symbol in the card body for this run, and a Poké Ball for Trainers.',
    'The twelve glyphs are STYLISED GEOMETRIC DRAWINGS made for this build. They are not the official icons, and no sheet is verified against a photograph.',
    'The symbol is chosen from the card row, never guessed: a Trainer gets the Poké Ball, a Pokémon gets its first recognised type, and an unknown type renders plain foil rather than the wrong symbol.',
    `Of ${eligible.length} reverse printings in this catalogue, ${knownGlyph.length} carry a type (or Trainer supertype) the loader can act on and ${eligible.length - knownGlyph.length} do not, so those cards show plain foil.`,
    'The sheets tile: glyphs are stamped with wrap-around, so the paper repeats across a card. Whether the real print repeated is not documented here; tiling is this build’s disclosed choice.',
    'Coverage is the card body, apart from the illustration window, which is the mask the reverse table records for this run.',
  ],
}

fs.mkdirSync('reports', { recursive: true })
fs.writeFileSync('reports/type-symbol-printings.json', JSON.stringify(report, null, 2) + '\n')

const lines: string[] = []
lines.push('# Type-symbol reverse paper — BW2–11 and XY')
lines.push('')
lines.push(`Generated by \`${report.generated}\`. Phase 5F of \`HOLOFOIL_ROADMAP.md\`.`)
lines.push('')
lines.push('## Numbers')
lines.push('')
lines.push(`- Expansions on this paper: **${counts.expansions}** (${counts.validated} validated).`)
lines.push(`- Reverse printings in this catalogue: **${counts.reversePrintings}**.`)
lines.push(`- Printings whose type the loader can use: **${counts.printingsWithKnownType}**; the other ${counts.printingsWithoutType} render plain foil.`)
lines.push(`- Glyph sheets: **${counts.glyphs}** (one per type plus the Trainer Poké Ball).`)
lines.push(`- Texture verified against a card: **${counts.textureVerified ? 'yes' : 'no — stylised reconstruction'}**.`)
lines.push('')
lines.push('## What is verified and what is drawn')
lines.push('')
for (const h of report.honesty) lines.push(`- ${h}`)
lines.push('')
lines.push('## Glyphs')
lines.push('')
lines.push('| glyph | sheet | coverage | peak | wrap |')
lines.push('| --- | --- | --- | --- | --- |')
for (const g of report.glyphs) {
  lines.push(`| ${g.id} | \`${g.texture}\` | ${(g.coverage * 100).toFixed(2)}% | ${g.peak.toFixed(3)} | ${g.seamRatio.toFixed(3)} |`)
}
lines.push('')
lines.push('## Expansions')
lines.push('')
lines.push('| set | name | year | mask | validated |')
lines.push('| --- | --- | --- | --- | --- |')
for (const e of report.expansions) {
  lines.push(`| \`${e.setId}\` | ${e.name} | ${e.year} | ${e.mask === 'outside-art' ? 'body' : 'window'} | ${e.implemented ? 'yes' : 'no'} |`)
}
lines.push('')
if (problems.length) {
  lines.push('## Problems')
  lines.push('')
  for (const p of problems) lines.push(`- ${p}`)
  lines.push('')
}
fs.writeFileSync('reports/type-symbol-printings.md', lines.join('\n'))

console.log(`expansions: ${counts.expansions} (${counts.validated} validated) · printings: ${counts.reversePrintings}`)
console.log(`glyphs: ${counts.glyphs} · printings with a usable type: ${counts.printingsWithKnownType}/${counts.reversePrintings}`)
console.log('written: reports/type-symbol-printings.json, reports/type-symbol-printings.md')
if (problems.length) {
  console.log(`PROBLEMS (${problems.length}):`)
  for (const p of problems) console.log(' -', p)
  process.exitCode = 1
} else {
  console.log('all 24 expansions use the body mask and are validated')
}
